/**
 * Generates design/ds-bot-patches.hunks.md from design/ds-bot-patches.patch.
 *
 * The ledger must be mechanical: hand-written line numbers were wrong three times, and so
 * were hand-written totals. This writes both the statistics and the table, from the patch
 * alone; nothing else is touched.
 *
 *   node tools/patch-ledger.mjs > design/ds-bot-patches.hunks.md
 */
import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const patchPath = resolve(root, 'design/ds-bot-patches.patch')
const patch = readFileSync(patchPath, 'utf8')

const HUNK = /^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@/

const hunks = []
let file = null
let files = 0
let added = 0
let removed = 0
const removedPerFile = new Map()
for (const line of patch.split('\n')) {
  if (line.startsWith('+++ b/')) {
    file = line.slice(6)
    files++
    continue
  }
  if (line.startsWith('--- ')) continue

  const head = HUNK.exec(line)
  if (head) {
    hunks.push({ file, start: Number(head[3]), end: Number(head[3]), count: 0, next: Number(head[3]) })
    continue
  }

  if (file !== null && line.startsWith('-')) removedPerFile.set(file, (removedPerFile.get(file) ?? 0) + 1)
  if (file !== null && line.startsWith('+')) added++
  if (file !== null && line.startsWith('-')) removed++

  const hunk = hunks[hunks.length - 1]
  if (!hunk || file === null) continue
  if (line.startsWith('+')) {
    if (hunk.count === 0) hunk.start = hunk.next
    hunk.end = hunk.next
    hunk.count++
    hunk.next++
  } else if (line.startsWith(' ')) {
    hunk.next++
  }
}

hunks.sort((a, b) => (a.file < b.file ? -1 : a.file > b.file ? 1 : a.start - b.start || a.end - b.end))

const rows = hunks.map((hunk, i) => {
  const range = hunk.start === hunk.end ? `${hunk.start}` : `${hunk.start}–${hunk.end}`
  return `| ${i + 1} | \`${hunk.file}\` | ${range} | ${hunk.count} |`
})

// Deleted lines are what a merge or an upgrade argues about, so the heaviest files lead.
const heaviest = [...removedPerFile].filter(([, count]) => count > 0).sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1))
const heaviestTable = ['| 文件 | 删除行 |', '|---|---|', ...heaviest.slice(0, 10).map(([name, count]) => `| \`${name}\` | ${count} |`)].join('\n')

const statistics = [
  '| 项 | 值 |',
  '|---|---|',
  `| 文件 | ${files} |`,
  `| hunks | ${hunks.length} |`,
  `| 新增行 | ${added} |`,
  `| 删除行 | ${removed} |`,
].join('\n')

process.stdout.write([
  '<!-- Generated by tools/patch-ledger.mjs from design/ds-bot-patches.patch. Do not edit by hand. -->',
  '',
  '## 统计',
  '',
  statistics,
  '',
  '删除行最多的文件（前 10）：',
  '',
  heaviestTable,
  '',
  '## 新增行号',
  '',
  '| # | 文件 | 新增行号 | 新增数 |',
  '|---|---|---|---|',
  ...rows,
  '',
].join('\n'))
