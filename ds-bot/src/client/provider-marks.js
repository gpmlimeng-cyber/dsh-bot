// The provider a model reports is whatever the host calls it, so the map is keyed by the
// names that show up rather than by one id scheme: deepseek-official, xiaomi-token-plan-cn
// and moonshotai-cn all have to land on a vendor.
const ALIASES = {
  deepseek: ['deepseek'],
  openai: ['openai', 'codex', 'chatgpt', 'gpt'],
  anthropic: ['anthropic', 'claude'],
  google: ['google', 'gemini', 'vertex'],
  xai: ['xai', 'grok'],
  moonshot: ['moonshot', 'kimi'],
  qwen: ['qwen', 'alibaba', 'dashscope'],
  xiaomi: ['xiaomi', 'mimo'],
  minimax: ['minimax'],
  bytedance: ['bytedance', 'doubao', 'volcengine'],
  meta: ['meta', 'llama'],
  mistral: ['mistral'],
}

function markFor(name) {
  const key = String(name ?? '').toLowerCase().replace(/[^a-z0-9]/g, '')
  if (!key) return undefined
  if (MARKS[key]) return { id: key, ...MARKS[key] }
  for (const [id, names] of Object.entries(ALIASES)) {
    if (names.some((alias) => key.includes(alias))) return { id, ...MARKS[id] }
  }
  return undefined
}

/** The provider's mark, or null when the provider is one we have no drawing for. */
export function ProviderMark({ name, size = 16 }) {
  const mark = markFor(name)
  if (!mark) return null
  return h('svg', {
    className: 'bt-provider-mark', width: size, height: size, viewBox: mark.viewBox,
    fill: mark.fill, 'aria-hidden': true, 'data-provider': mark.id,
  }, mark.paths.map((d, index) => h('path', { key: index, d })))
}
